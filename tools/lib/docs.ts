/** Renders the generated canon and tables that `docs:check` verifies. */

import type { ContentIndex } from '../../src/engine/content'
import { flagUses, factWriters } from './flags'

export interface CanonWant {
  id: string
  text: string
  stake: string
  scene: string
}

export function castJson(index: ContentIndex): string {
  const rows = [...index.characters.values()]
    .sort((a, b) => a.id.localeCompare(b.id))
    .map((character) => ({
      id: character.id,
      name: character.name,
      tier: character.tier,
      dialogue: character.dialogue ?? null,
      wants: (character.wants ?? []).map((want) =>
        typeof want === 'string'
          ? { id: want, text: want, stake: '', scene: '' }
          : { id: want.id, text: want.text, stake: want.stake, scene: want.scene },
      ),
      voice: character.voice
        ? {
            register: character.voice.register,
            address: character.voice.address ?? [],
            tics: character.voice.tics ?? [],
            avoid: character.voice.avoid ?? [],
            maxSentenceWords: character.voice.maxSentenceWords ?? null,
            sampleLines: character.voice.sampleLines ?? [],
          }
        : null,
      ties: character.ties ?? [],
      knowledge: character.knowledge ?? [],
      appearances: character.appearances ?? [],
    }))
  return `${JSON.stringify({ characters: rows }, null, 2)}\n`
}

export function factsJson(index: ContentIndex): string {
  const writers = factWriters(index)
  const facts = new Set(writers.keys())
  for (const character of index.characters.values()) {
    for (const knowledge of character.knowledge ?? []) facts.add(knowledge.fact)
  }
  const rows = [...facts].sort().map((fact) => ({
    id: fact,
    taughtBy: [...new Set(writers.get(fact) ?? [])].sort(),
  }))
  return `${JSON.stringify({ facts: rows }, null, 2)}\n`
}

function table(headers: string[], rows: string[][]): string {
  return [
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map((cell) => cell.replaceAll('|', '\\|')).join(' | ')} |`),
  ].join('\n')
}

export function castTable(index: ContentIndex): string {
  const rows = [...index.characters.values()]
    .filter((character) => character.tier === 'major' || character.tier === 'recurring')
    .sort((a, b) => a.id.localeCompare(b.id))
    .map((character) => [
      character.name,
      character.tier,
      (character.wants ?? [])
        .map((want) => (typeof want === 'string' ? want : `${want.id} (${want.scene})`))
        .join('; '),
      (character.ties ?? []).map((tie) => `${tie.kind}: ${tie.character}`).join('; '),
    ])
  return `# Cast\n\nGenerated by \`pnpm docs:sync\`. Edit the character JSON, not this table.\n\n${table(
    ['Character', 'Tier', 'Wants', 'Ties'],
    rows,
  )}\n`
}

export function flagTable(index: ContentIndex): string {
  const rows = [...flagUses(index).values()]
    .sort((a, b) => a.flag.localeCompare(b.flag))
    .map((use) => [
      use.flag,
      String(new Set(use.writer).size),
      String(new Set(use.reader).size),
      [...new Set(use.reader)].slice(0, 3).join('; ') || '(terminal)',
    ])
  return `# Flags\n\nGenerated by \`pnpm docs:sync\`.\n\n${table(
    ['Flag', 'Writers', 'Readers', 'Read by'],
    rows,
  )}\n`
}

export function sceneTable(index: ContentIndex): string {
  const rows = [...index.dialogues.values()]
    .filter((dialogue) => dialogue.scene)
    .sort((a, b) => a.id.localeCompare(b.id))
    .map((dialogue) => [
      dialogue.id,
      dialogue.scene?.goal ?? '',
      dialogue.scene?.turn ?? '',
      dialogue.scene?.callback ?? '',
    ])
  return `# Scene contracts\n\nGenerated by \`pnpm docs:sync\`.\n\n${table(
    ['Scene', 'Goal', 'Turn', 'Callback'],
    rows,
  )}\n`
}

/** Every file `docs:sync` writes; `docs:check` verifies the same map. */
export const GENERATED: Record<string, (index: ContentIndex) => string> = {
  'docs/design/cast.json': castJson,
  'docs/design/facts.json': factsJson,
  'docs/design/generated/cast.md': castTable,
  'docs/design/generated/flags.md': flagTable,
  'docs/design/generated/scenes.md': sceneTable,
  'docs/design/generated/prices.md': priceTable,
}

export function priceTable(index: ContentIndex): string {
  const rows: string[][] = []
  for (const dialogue of index.dialogues.values()) {
    for (const [nodeId, node] of Object.entries(dialogue.nodes)) {
      const prices = new Set<string>()
      const texts = [node.text, ...node.choices.map((choice) => choice.text)]
      for (const text of texts) {
        for (const match of text.matchAll(/\b(\d+|[a-z]+)\s+shekels?\b/gi)) {
          if (match[0]) prices.add(match[0].toLowerCase())
        }
      }
      if (prices.size > 0) rows.push([dialogue.id, nodeId, [...prices].join(', ')])
    }
  }
  rows.sort((a, b) => `${a[0]}:${a[1]}`.localeCompare(`${b[0]}:${b[1]}`))
  return `# Prices named in prose\n\nGenerated by \`pnpm docs:sync\`. \`pnpm price:check\` matches these to effects.\n\n${table(
    ['Scene', 'Node', 'Named'],
    rows,
  )}\n`
}
